void DisplayManager::updateMainScreen(float avgSpeed, float dist, float minutes, int sats, float currentSpm, int hour, int minute, float* avgCurve, float ratio) {
    int splitMin = 0, splitSec = 0;
    if (avgSpeed > 0.5) {
        float totalSecFor500m = 1800.0 / avgSpeed; 
        splitMin = (int)(totalSecFor500m / 60);
        splitSec = (int)(totalSecFor500m) % 60;
    }
    String status = (currentSpm > 0) ? "ROWING" : "STATIONARY";
    
    // Coordinate Helpers
    int classicMidX = display.width() / 2;
    int classicMidY = ((display.height() - 25) / 2) + 25;
    int newMidX = 110;
    int newMidY = ((display.height() - 26) / 2) + 26;

    // 1. TOP BAR (Shared)
    if (sats != lastDispSats || status != lastDispStatus) {
        char timeBuf[6]; sprintf(timeBuf, "%02d:%02d", hour, minute);
        display.setPartialWindow(0, 0, display.width(), 20);
        display.firstPage();
        do {
            display.fillScreen(GxEPD_WHITE);
            display.setTextSize(1);
            display.setCursor(5, 8); display.print("Sats: "); display.print(sats);
            display.setCursor(display.width() - 40, 8); display.print(timeBuf);
            int16_t x1, y1; uint16_t w, h;
            display.setTextSize(2);
            display.getTextBounds(status, 0, 0, &x1, &y1, &w, &h);
            display.setCursor((display.width()/2)-(w/2), 6); display.print(status);
        } while (display.nextPage());
        lastDispSats = sats; lastDispStatus = status;
    }

    // 2. SPLIT/PACE
    if (splitMin != lastDispSplitMin || splitSec != lastDispSplitSec) {
        int wX = 0, wY = 42, wW = (useClassicUI) ? classicMidX - 20 : newMidX - 5, wH = 40;
        display.setPartialWindow(wX, wY, wW, wH); 
        display.firstPage();
        do {
            display.fillScreen(GxEPD_WHITE);
            display.setTextSize(3); display.setCursor(10, 50); 
            if (avgSpeed > 0.5) {
                display.print(splitMin); display.print(":");
                if (splitSec < 10) {
                    display.print("0");
                }
                display.print(splitSec);
            } else { display.print("--:--"); }
        } while (display.nextPage());
        lastDispSplitMin = splitMin; lastDispSplitSec = splitSec;
    }

    // 3. STROKE RATE
    if ((int)currentSpm != (int)lastDispSpm) {
        int wX = (useClassicUI) ? classicMidX + 10 : 0;
        int wY = (useClassicUI) ? 42 : newMidY + 23;
        int wW = (useClassicUI) ? classicMidX - 45 : newMidX - 5;
        int wH = 40;
        
        display.setPartialWindow(wX, wY, wW, wH); 
        display.firstPage();
        do {
            display.fillScreen(GxEPD_WHITE); display.setTextSize(4);
            int curX = (useClassicUI) ? classicMidX + 20 : 15;
            int curY = (useClassicUI) ? 50 : newMidY + 30;
            display.setCursor(curX, curY); display.print((int)currentSpm);
        } while (display.nextPage());
        lastDispSpm = (int)currentSpm;
    }

    // 4. CLASSIC UI: DISTANCE & TIME
    if (useClassicUI) {
        if ((int)dist != lastDispDist) {
            display.setPartialWindow(10, classicMidY + 23, classicMidX - 35, 40); 
            display.firstPage();
            do {
                display.fillScreen(GxEPD_WHITE); display.setTextSize(4);
                display.setCursor(15, classicMidY + 30); display.print((int)dist);
            } while (display.nextPage());
            lastDispDist = (int)dist;
        }

        if ((int)minutes != lastDispMin) {
            display.setPartialWindow(classicMidX + 10, classicMidY + 23, classicMidX - 50, 40); 
            display.firstPage();
            do {
                display.fillScreen(GxEPD_WHITE); display.setTextSize(4);
                display.setCursor(classicMidX + 20, classicMidY + 30); display.print((int)minutes);
            } while (display.nextPage());
            lastDispMin = (int)minutes;
        }
    } 
    // 5. NEW UI: CURVE & RATIO
    else {
        // ALWAYS redraw the graph if we have an array, so the user sees live technique changes
        if (avgCurve != nullptr && currentSpm > 0) {
            int ratioY = display.height() - 25;
            int boxX = newMidX + 1;
            int boxY = 27;
            int boxW = display.width() - newMidX - 1;
            int boxH = ratioY - 27;

            display.setPartialWindow(boxX, boxY, boxW, boxH);
            display.firstPage();
            do {
                display.fillScreen(GxEPD_WHITE);
                
                // Find min/max dynamically to scale the graph perfectly
                float minVal = avgCurve[0];
                float maxVal = avgCurve[0];
                for (int i = 1; i < 100; i++) {
                    if (avgCurve[i] < minVal) minVal = avgCurve[i];
                    if (avgCurve[i] > maxVal) maxVal = avgCurve[i];
                }
                
                float range = maxVal - minVal;
                if (range < 0.1f) range = 0.1f; // Prevent div by zero if flatline

                // Draw the 100-point curve
                for (int i = 0; i < 99; i++) {
                    int x1 = boxX + 5 + (i * (boxW - 10)) / 99;
                    int y1 = boxY + boxH - 5 - ((avgCurve[i] - minVal) / range) * (boxH - 10);
                    
                    int x2 = boxX + 5 + ((i + 1) * (boxW - 10)) / 99;
                    int y2 = boxY + boxH - 5 - ((avgCurve[i+1] - minVal) / range) * (boxH - 10);
                    
                    display.drawLine(x1, y1, x2, y2, GxEPD_BLACK);
                }
            } while (display.nextPage());
        }

        // Draw the Ratio Number
        if (abs(ratio - lastDispRatio) > 0.01) {
            int ratioY = display.height() - 25;
            display.setPartialWindow(newMidX + 50, ratioY + 2, display.width() - newMidX - 50, 20);
            display.firstPage();
            do {
                display.fillScreen(GxEPD_WHITE);
                display.setTextSize(2);
                display.setCursor(newMidX + 55, ratioY + 5);
                display.print(ratio, 2); // Print to 2 decimal places (e.g. "0.45")
            } while (display.nextPage());
            lastDispRatio = ratio;
        }
    }
}

void DisplayManager::drawBluetoothScreen() {
    display.setFullWindow();
    display.firstPage();
    do {
        display.fillScreen(GxEPD_WHITE);
        
        int logoX = (display.width() - 100) / 2;
        int logoY = (display.height() - 100) / 2;
        
        display.drawBitmap(logoX, logoY, epd_bitmap_bluetooth, 100, 100, GxEPD_BLACK);
        
    } while (display.nextPage());
}